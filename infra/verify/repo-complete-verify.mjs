/**
 * repo-complete-verify.mjs — the repository is the whole record of what runs.
 *
 * WHY THIS EXISTS. services/market-data/internal/vendor/polygon.go ran in
 * production for as long as market-data did and was never in the repository. A
 * bare `vendor/` in .gitignore, written for Go dependency vendoring, matched the
 * project's own internal/vendor package, and a fresh clone could not build
 * market-data at all.
 *
 * NOTHING CAUGHT IT, AND THE REASON MATTERS. deployed-version-verify checks that
 * what is running is what was committed — and a file that was never committed
 * cannot fail that comparison, because there is nothing to compare it to. It
 * passed by being invisible. The backups cover Postgres and MinIO, not
 * /home/ubuntu/arcana, so the only copy of that file was on one machine.
 *
 * So the question this answers is not "is anything else missing" — it is "how
 * would we know". It does not read .gitignore and reason about it. It clones the
 * repository into a clean directory, builds every module from that clone, and
 * compares the running tree against the checked-out one file by file. Every path
 * that exists only on the running machine must match a DECLARED category below.
 * An unclassified one fails, which is the whole point: a file nobody has decided
 * about is exactly how the last one survived.
 *
 * IT WRITES NOTHING. A clone, some builds, and a diff.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { suite } from './lib/sections.mjs';

const REPO = process.env.REPO || '/home/ubuntu/arcana';
const { check, section, nothingToCheck, report } = suite('repo-complete-verify');

const run = (cmd, args, cwd) =>
  execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();

// WHAT IS ALLOWED TO EXIST ONLY ON THE RUNNING MACHINE, and why. Anything not
// matched here fails. Keep the reasons: a category nobody can justify is a
// category that will one day hide a source file.
const ALLOWED = [
  {
    what: 'compiled output',
    why: 'rebuilt by the installer from the commit it stamps; never the source of anything',
    is: (p) => ['dist', 'tsconfig.tsbuildinfo', 'server', 'backfill', 'scheduler-bin',
      '.dust-verify-build', '.guard-verify-race'].includes(p.name),
  },
  {
    what: 'test and verify logs',
    why: 'written by `make test-go` and by run-all.mjs; ignored on purpose and named in .gitignore',
    is: (p) => p.name === '.test-logs' || p.name === '.verify-logs',
  },
  {
    what: 'secrets and machine config',
    why: 'must NOT be committed. Their SHAPE should be, as .env.example — see the note below',
    is: (p) => p.name === '.env' || (p.name.startsWith('.env.') && p.name !== '.env.example'),
  },
  {
    what: 'npm-managed dependencies',
    why: 'reproduced from package-lock.json, which is committed',
    is: (p) => p.name === 'node_modules',
  },
];
// go.work.sum HAD A CATEGORY HERE and no longer does. It was excused as
// "regenerated by the toolchain", which is not the same claim as "regenerated
// identically" — what the toolchain writes depends on which module versions it
// happens to need at the time. go.work is committed, so its sums are part of the
// same record and are committed too. Removing the category is the point: if it
// ever leaves the repository again, it becomes an unclassified file and fails
// here rather than being waved through by an excuse nobody re-examines.

const tmp = mkdtempSync(join(tmpdir(), 'repo-complete-'));
const clone = join(tmp, 'clone');
let cloned = false;
let sameCommit = false;

try {
  await section('The repository can be cloned, and is the commit that is running', async () => {
    const origin = run('git', ['-C', REPO, 'remote', 'get-url', 'origin']);
    run('git', ['clone', '--quiet', origin, clone]);
    cloned = existsSync(join(clone, '.git'));
    check('a clean clone of origin succeeds', cloned, `nothing was cloned into ${clone}`);
    if (!cloned) return;
    const here = run('git', ['-C', REPO, 'rev-parse', 'HEAD']);
    const there = run('git', ['-C', clone, 'rev-parse', 'HEAD']);
    sameCommit = here === there;
    check('the clone is at the commit the machine is running', sameCommit,
      `the machine is at ${here.slice(0, 8)} and origin's default branch is at ${there.slice(0, 8)}. ` +
      'Unpushed commits mean the repository is not yet the record of this machine');
    const dirty = run('git', ['-C', REPO, 'status', '--porcelain', '--untracked-files=no']);
    check('no tracked file on the machine differs from the commit', dirty === '',
      `uncommitted edits to tracked files: ${dirty.split('\n').join(', ')}`);
  });

  await section('Every module in go.work builds from the clone alone', async () => {
    if (!cloned) {
      nothingToCheck('there is no clone to build, which the section above has already failed');
      return;
    }
    const work = readFileSync(join(clone, 'go.work'), 'utf8');
    const mods = [...work.matchAll(/^\s*(\.\/[^\s)]+)\s*$/gm)].map((m) => m[1]);
    check('go.work lists the modules', mods.length > 0, 'no `use` entries were parsed out of go.work');
    for (const m of mods) {
      let err = '';
      try {
        run('go', ['build', './...'], join(clone, m));
      } catch (e) {
        err = String(e.stderr || e.message).split('\n').slice(0, 2).join(' ').trim();
      }
      check(`${m} builds from a clone with nothing else present`, err === '', err);
    }
  });

  await section('Nothing runs here that the repository does not contain', async () => {
    if (!cloned) {
      nothingToCheck('there is no clone to compare against');
      return;
    }
    // diff reports a directory that exists on one side only as a single line and
    // does not walk into it, so node_modules and dist cost nothing here.
    let out = '';
    try {
      out = run('diff', ['-rq', '--exclude=.git', clone, REPO]);
    } catch (e) {
      out = String(e.stdout || '').trim();
    }
    const lines = out ? out.split('\n') : [];

    const onlyHere = [];
    const onlyThere = [];
    const differ = [];
    for (const l of lines) {
      let m = l.match(/^Only in (.*): (.*)$/);
      if (m) {
        const dir = m[1];
        const entry = { dir, name: m[2], path: join(dir, m[2]) };
        if (dir.startsWith(REPO)) onlyHere.push(entry);
        else onlyThere.push(entry);
        continue;
      }
      m = l.match(/^Files (.*) and (.*) differ$/);
      if (m) differ.push(m[2]);
    }

    check('no committed file is missing from the running tree', onlyThere.length === 0,
      `absent here: ${onlyThere.map((e) => e.name).join(', ')}`);
    // Only meaningful when the machine is ON the commit the clone holds. If it is
    // behind, every difference is explained by the skew the first section already
    // reported, and repeating it here would state a consequence as a cause.
    if (sameCommit) {
      check('no committed file has been edited in place on the machine', differ.length === 0,
        `differs from the commit: ${differ.join(', ')}`);
    } else if (differ.length > 0) {
      console.log(`      NOTE  ${differ.length} file(s) differ from the clone, which is expected ` +
        'while this machine is behind origin; re-run after pulling to test this properly.');
    }

    // The one that would have caught polygon.go.
    const unclassified = [];
    const byCategory = new Map();
    for (const e of onlyHere) {
      const cat = ALLOWED.find((c) => c.is(e));
      if (!cat) unclassified.push(e);
      else byCategory.set(cat.what, (byCategory.get(cat.what) || 0) + 1);
    }
    for (const [what, n] of byCategory) console.log(`      ${n} x ${what}`);
    check('every path that exists only on this machine is one we have decided about',
      unclassified.length === 0,
      `${unclassified.length} unclassified: ` +
      unclassified.map((e) => e.path.replace(REPO, '')).join(', ') +
      '. A file running in production that the repository does not contain cannot be compared to ' +
      'any commit, is not in any backup, and exists on exactly one machine. Commit it, or add a ' +
      'category here saying why it must not be');
  });

  await section('The shape of the machine config is recorded, even though its values are not', async () => {
    if (!cloned) {
      nothingToCheck('there is no clone to read the committed examples from');
      return;
    }
    // Any *.example is a template, not a file needing one of its own — and the
    // templates are now named .env.auth.example, .env.llm.example and so on, so
    // matching only the literal '.env.example' would have sent this looking for
    // a .env.auth.example.example.
    const present = run('bash', ['-c',
      `cd ${REPO} && find . -name '.env*' -not -path './node_modules/*' -not -path './.git/*' | sort`])
      .split('\n').filter(Boolean).filter((p) => !p.endsWith('.example'));
    const examples = new Set(run('git', ['-C', clone, 'ls-files']).split('\n')
      .filter((p) => p.endsWith('.example')));
    // PER FILE, not per directory. .env.auth, .env.alerts and .env.llm each hold
    // their own keys; treating the root .env.example as covering all of them would
    // report three undocumented files as documented, which is the leniency this
    // whole exercise exists to remove. A plain .env is documented by
    // .env.example beside it; .env.auth needs .env.auth.example.
    const undocumented = present.filter((p) => {
      const rel = p.replace(/^\.\//, '');
      const i = rel.lastIndexOf('/');
      const dir = i < 0 ? '' : rel.slice(0, i + 1);
      const name = i < 0 ? rel : rel.slice(i + 1);
      return !examples.has(`${dir}${name}.example`) &&
        !(name === '.env' && examples.has(`${dir}.env.example`));
    });
    check('at least one example is committed', examples.size > 0,
      'nothing records what any service needs in its environment');

    // A FAILURE NOW, not a note. It was a note while four files were missing
    // theirs, because a suite that is permanently red over known work teaches
    // people to stop reading it. The four exist, so from here an env file
    // without an example is a NEW gap, and a new gap should be red.
    //
    // The values stay out of git; the KEY NAMES go in. A machine nobody can
    // configure is the same class of problem as a repository that is not the
    // whole record of what runs, which is what this file was written for.
    check('every env file on this machine has a committed example beside it',
      undocumented.length === 0,
      `${undocumented.length} without one: ${undocumented.join(', ')}. ` +
      'Add <name>.example holding the key names and no values — a new machine cannot be ' +
      'configured from key names nobody wrote down');
    console.log(`      ${present.length} env file(s) here, ${examples.size} example(s) committed`);
  });
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const code = report();
if (code !== 0) process.exit(code);
console.log('repo-complete-verify: the repository contains everything that runs here.');
